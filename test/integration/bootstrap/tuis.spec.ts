#!/usr/bin/env bun
// The TUI launcher's Raycast side (docs/superpowers/specs/2026-11-12-tui-launcher-design.md): script/tuis-build.ts
// turns config/tuis.toml into one Raycast Script Command per entry, each calling `yb tui`.
import { afterEach, beforeEach, describe, expect, it } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "../../..");
const BUILD = join(ROOT, "script/tuis-build.ts");
const HEADER = "# Generated by mise run tuis:build from config/tuis.toml; do not edit.";

let dir = "";
let toml = "";
let out = "";
beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "tuis-"));
  toml = join(dir, "tuis.toml");
  out = join(dir, "tuis");
});
afterEach(() => rmSync(dir, { recursive: true, force: true }));

function build(body: string | null, ...args: string[]) {
  if (body !== null) writeFileSync(toml, body);
  const r = Bun.spawnSync(["bun", BUILD, ...args], {
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, DOTS_TUIS_TOML: toml, DOTS_TUIS_DIR: out },
  });
  return { code: r.exitCode, out: r.stdout.toString() + r.stderr.toString() };
}
const script = (name: string) => readFileSync(join(out, `${name}.sh`), "utf8");

describe("tuis:build", () => {
  it("writes one Raycast command per entry", () => {
    expect(build('[psc]\ntitle = "Copy a secret"\ncommand = "psc"\nicon = "🔑"\n').code).toBe(0);
    expect(script("psc")).toBe(
      [
        "#!/bin/zsh",
        HEADER,
        "# @raycast.schemaVersion 1",
        "# @raycast.title Copy a secret",
        "# @raycast.mode silent",
        "# @raycast.packageName TUIs",
        "# @raycast.icon 🔑",
        'export PATH="/opt/homebrew/bin:/usr/bin:/bin:$PATH"',
        'exec "$HOME/.local/bin/yb" tui psc --command psc --width 875 --height 600',
        "",
      ].join("\n"),
    );
    expect(statSync(join(out, "psc.sh")).mode & 0o111).toBeTruthy();
  });

  it("defaults the title to the name and passes size and pause", () => {
    build('[btop]\ncommand = "btop"\nsize = [1000, 700]\npause = true\n');
    const s = script("btop");
    expect(s).toContain("# @raycast.title btop\n");
    expect(s).not.toContain("@raycast.icon");
    expect(s.trimEnd().endsWith("--width 1000 --height 700 --pause")).toBe(true);
  });

  it("quotes commands with spaces", () => {
    build("[dust]\ncommand = \"bash -c 'dust; read -n 1 -s'\"\n");
    expect(script("dust")).toContain(String.raw`--command 'bash -c '\''dust; read -n 1 -s'\'''`);
  });

  it("removes scripts whose entry is gone", () => {
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, "old.sh"), `#!/bin/zsh\n${HEADER}\n`);
    writeFileSync(join(out, "mine.sh"), "#!/bin/zsh\necho hand-written\n");
    build('[psc]\ncommand = "psc"\n');
    expect(existsSync(join(out, "old.sh"))).toBe(false);
    expect(existsSync(join(out, "mine.sh"))).toBe(true);
  });

  it("refuses a bad name or a missing command", () => {
    const bad = build('["my tui"]\ncommand = "x"\n');
    expect(bad.code).toBe(1);
    expect(bad.out).toContain("my tui");
    const none = build("[psc]\n");
    expect(none.code).toBe(1);
    expect(none.out).toContain("psc");
  });

  describe("--check", () => {
    it("passes right after a build and fails on a stale script", () => {
      build('[psc]\ncommand = "psc"\n');
      expect(build(null, "--check").code).toBe(0);
      writeFileSync(join(out, "psc.sh"), "edited\n");
      const r = build(null, "--check");
      expect(r.code).toBe(1);
      expect(r.out).toContain("tuis:build");
    });

    it("fails on a generated script with no entry", () => {
      build('[psc]\ncommand = "psc"\n');
      writeFileSync(join(out, "old.sh"), `#!/bin/zsh\n${HEADER}\n`);
      expect(build(null, "--check").code).toBe(1);
    });

    it("the committed scripts are current", () => {
      const r = Bun.spawnSync(["bun", BUILD, "--check"], { stdout: "pipe", stderr: "pipe" });
      expect(r.stderr.toString()).toBe("");
      expect(r.exitCode).toBe(0);
    });
  });

  it("is a mise task with a documented --check flag", () => {
    const task = Bun.TOML.parse(readFileSync(join(ROOT, "mise.toml"), "utf8")) as {
      tasks: Record<string, { usage?: string; run?: string }>;
    };
    expect(task.tasks["tuis:build"]?.usage).toContain('flag "--check"');
  });
});
