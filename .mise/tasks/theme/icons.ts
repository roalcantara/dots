#!/usr/bin/env bun
//MISE description="Colour a theme's eza icons per file, the VS Code way (nvim-web-devicons' colours)"
//USAGE arg "[name]" help="Theme folder in config/theme/themes" default="tokyonight-storm-custom"
// Writes the `filenames:` and `extensions:` sections of the theme's eza/theme.yml between the BEGIN/END devicons
// markers (appended when absent): only each icon's colour, so file names keep their LS_COLORS colours and eza keeps
// its own glyphs. Rerunning replaces the block, hand edits inside it included. Data: nvim-web-devicons (MIT).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO = "https://raw.githubusercontent.com/nvim-tree/nvim-web-devicons/master/lua/nvim-web-devicons/default";
const BEGIN = "# BEGIN devicons";
const END = "# END devicons";

const root = (await Bun.$`git rev-parse --show-toplevel`.text()).trim();
const name = process.argv[2] || "tokyonight-storm-custom";
const file = join(root, "config/theme/themes", name, "eza/theme.yml");
if (!existsSync(file)) throw new Error(`theme:icons: no ${file}`);

// Entries look like `["license"] = { icon = "…", color = "#D0BF41", cterm_color = "185", name = "License" },`.
const parse = (lua: string) =>
  [...lua.matchAll(/^\s*\["([^"]+)"\]\s*=\s*\{[^}]*color\s*=\s*"(#[0-9A-Fa-f]{6})"/gm)].map(([, key, color]) => ({
    key,
    color: color.toLowerCase(),
  }));
const fetchLua = async (part: string) => {
  const res = await fetch(`${REPO}/${part}.lua`);
  if (!res.ok) throw new Error(`theme:icons: ${part}.lua: HTTP ${res.status}`);
  return parse(await res.text());
};
const [byName, byExt] = await Promise.all([fetchLua("icons_by_filename"), fetchLua("icons_by_file_extension")]);

// eza matches file names by exact case (devicons ignores case) and extensions in any case: give each name its usual
// spellings, license → LICENSE and License, readme.md → README.md and Readme.md.
const spellings = (key: string) => {
  const dot = key.indexOf(".", 1);
  const [stem, rest] = dot > 0 ? [key.slice(0, dot), key.slice(dot)] : [key, ""];
  const cap = (s: string) => s.replace(/^(\.?)(.)/, (_, d, c) => d + c.toUpperCase());
  return [...new Set([key, stem.toUpperCase() + rest, cap(stem) + rest])];
};
const yamlKey = (k: string) => `'${k.replaceAll("'", "''")}'`;
const line = (k: string, color: string) => `  ${yamlKey(k)}: {icon: {style: {foreground: '${color}'}}}`;

const names = new Map<string, string>();
for (const { key, color } of byName) for (const k of spellings(key)) if (!names.has(k)) names.set(k, color);
const exts = new Map<string, string>();
for (const { key, color } of byExt) exts.set(key.toLowerCase(), color);

const block = [
  BEGIN,
  `# Icon colours per file, from nvim-web-devicons (MIT, github.com/nvim-tree/nvim-web-devicons): generated by`,
  `# \`mise run theme:icons ${name}\`, which replaces this block, hand edits included.`,
  "filenames:",
  ...[...names].sort(([a], [b]) => a.localeCompare(b)).map(([k, c]) => line(k, c)),
  "extensions:",
  ...[...exts].sort(([a], [b]) => a.localeCompare(b)).map(([k, c]) => line(k, c)),
  END,
].join("\n");

const text = readFileSync(file, "utf8");
const start = text.indexOf(BEGIN);
const end = text.indexOf(END);
const next =
  start >= 0 && end > start
    ? text.slice(0, start) + block + text.slice(end + END.length)
    : `${text.replace(/\n*$/, "\n")}\n${block}\n`;
writeFileSync(file, next);
console.log(`theme:icons: ${names.size} file names and ${exts.size} extensions in ${file.slice(root.length + 1)}`);
