#!/usr/bin/env bash
# Regenerates config/zsh/opt/completions/_todo from `todo completion zsh`
# with custom helpers for task IDs and tags.
set -euo pipefail

out="${1:?usage: $0 <output-file>}"

content="$(todo completion zsh)"

substitutions=(
  ":id -- ID of the item:_default"
  ":id -- ID of the item:_todo_task_ids"
  ":id -- ID of the item to delete:_default"
  ":id -- ID of the item to delete:_todo_task_ids"
  ":id -- ID of the task:_default"
  ":id -- ID of the task:_todo_task_ids"
  ":TASK_ID:_default"
  ":TASK_ID:_todo_task_ids"
  ":TAG:_default"
  ":TAG:_todo_tags"
  ":PRIORITY:_default"
  ":PRIORITY:(low medium high)"
  ":SET:_default"
  ":SET:(todo en-cours done bloqued)"
  "md or yaml:_default"
  "md or yaml:(md yaml)"
)

# Verify all placeholders exist
for ((i = 0; i < ${#substitutions[@]}; i += 2)); do
  placeholder="${substitutions[i]}"
  if [[ "$content" != *"$placeholder"* ]]; then
    echo "todo-completion: placeholder not found: $placeholder" >&2
    exit 1
  fi
done

# Apply all substitutions
for ((i = 0; i < ${#substitutions[@]}; i += 2)); do
  placeholder="${substitutions[i]}"
  replacement="${substitutions[i + 1]}"
  content="${content//"$placeholder"/$replacement}"
done

header="#compdef todo
# Generated by script/todo-completion.sh (mise run zsh:completions:todo) from \`todo completion zsh\`; do not edit."

content="${content/#\#compdef todo/$header}"

tmp="$(mktemp "${out}.tmp.XXXXXX")"
printf '%s\n' "$content" > "$tmp"
mv "$tmp" "$out"
