#!/usr/bin/env bun
// Turns config/tuis.toml into one Raycast Script Command per TUI (config/raycast/scripts/tuis/<name>.sh),
// each running `yb tui` with that entry's values (docs/TILING.md, "TUIs"). Run `mise run tuis:build`;
// `--check` exits 1 when a committed script differs. DOTS_TUIS_TOML and DOTS_TUIS_DIR point it elsewhere (tests).
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const toml = process.env.DOTS_TUIS_TOML ?? join(ROOT, "config/tuis.toml");
const dir = process.env.DOTS_TUIS_DIR ?? join(ROOT, "config/raycast/scripts/tuis");
const HEADER = "# Generated by mise run tuis:build from config/tuis.toml; do not edit.";
const NAME = /^[a-z0-9][a-z0-9-]*$/;

interface Tui { title?: string; command?: string; icon?: string; size?: [number, number]; pause?: boolean }

const quote = (arg: string) => (/^[\w.+-]+$/.test(arg) ? arg : `'${arg.replaceAll("'", "'\\''")}'`);

function scripts(): Map<string, string> {
  const entries = Bun.TOML.parse(readFileSync(toml, "utf8")) as Record<string, Tui>;
  const problems: string[] = [];
  const out = new Map<string, string>();
  for (const [name, tui] of Object.entries(entries)) {
    if (!NAME.test(name)) problems.push(`${name}: names are lower-case letters, digits and dashes`);
    if (!tui.command) problems.push(`${name}: needs a command`);
    const [width, height] = tui.size ?? [875, 600];
    if (!Number.isInteger(width) || !Number.isInteger(height)) problems.push(`${name}: size is [width, height] in points`);
    if (problems.length) continue;
    const args = ["tui", name, "--command", quote(tui.command!), "--width", String(width), "--height", String(height)];
    if (tui.pause) args.push("--pause");
    out.set(name, [
      "#!/bin/zsh",
      HEADER,
      "# @raycast.schemaVersion 1",
      `# @raycast.title ${tui.title ?? name}`,
      "# @raycast.mode silent",
      "# @raycast.packageName TUIs",
      ...(tui.icon ? [`# @raycast.icon ${tui.icon}`] : []),
      'export PATH="/opt/homebrew/bin:/usr/bin:/bin:$PATH"',
      `exec "$HOME/.local/bin/yb" ${args.join(" ")}`,
      "",
    ].join("\n"));
  }
  if (problems.length) {
    for (const p of problems) console.error(`${toml}: ${p}`);
    process.exit(1);
  }
  return out;
}

// Scripts this generator wrote earlier (they carry the header); hand-written ones are left alone.
const generated = () =>
  existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".sh") && readFileSync(join(dir, f), "utf8").split("\n")[1] === HEADER)
    : [];

const wanted = scripts();
if (process.argv.includes("--check")) {
  const stale = [
    ...[...wanted].filter(([n, body]) => !existsSync(join(dir, `${n}.sh`)) || readFileSync(join(dir, `${n}.sh`), "utf8") !== body).map(([n]) => `${n}.sh`),
    ...generated().filter((f) => !wanted.has(f.slice(0, -3))),
  ];
  for (const f of stale) console.error(`stale: ${join(dir, f)} (run mise run tuis:build)`);
  process.exit(stale.length ? 1 : 0);
}
mkdirSync(dir, { recursive: true });
for (const f of generated()) if (!wanted.has(f.slice(0, -3))) rmSync(join(dir, f));
for (const [name, body] of wanted) {
  writeFileSync(join(dir, `${name}.sh`), body);
  chmodSync(join(dir, `${name}.sh`), 0o755);
}
